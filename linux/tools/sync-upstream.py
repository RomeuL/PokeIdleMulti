#!/usr/bin/env python3
"""Extract browser-only constants, without hand-translating the Windows scripts.

Run after syncing upstream; --check is used in CI. Business logic is compiled
directly from the original C# files by DeckBridge.csproj.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'linux/bridge/UpstreamScripts.g.cs'


def constant(source, name):
    match = re.search(r'private const string ' + name + r'\s*=', source)
    if not match:
        raise ValueError(f'Upstream constant missing: {name}')
    i = match.end()
    # Skip C# strings and comments so semicolons in JS cannot end a declaration.
    token = re.compile(r'"""[\s\S]*?"""|"(?:\\.|[^"\\])*"|//[^\n]*|/\*[\s\S]*?\*/')
    while i < len(source):
        part = token.match(source, i)
        if part:
            i = part.end()
        elif source[i] == ';':
            return source[match.start():i + 1].replace('private const', 'public const', 1)
        else:
            i += 1
    raise ValueError(f'Unterminated upstream constant: {name}')


def generate():
    sections = ['// Generated by linux/tools/sync-upstream.py. Do not edit.\n#nullable enable\nusing System.Globalization;\nnamespace PokeIdleMulti;\n']
    specs = {
        'GameScripts': ('AccountPane.cs', ['KeyScript', 'LoginScript', 'OpenScript', 'FrameLimitScript', 'SpriteLimitScript', 'UltraStateScript', 'SetUltraScript']),
        'BulkScripts': ('BulkRedeemDialog.cs', ['Pick', 'KickApi', 'TwitchReadBody', 'KickReadBody', 'TwitchRedeemBody', 'KickRedeemBody']),
        'LiveScripts': ('LivesWindow.cs', ['NoDrmScript', 'PlayScript']),
    }
    for cls, (file, names) in specs.items():
        source = (ROOT / 'PokeIdleMulti' / file).read_text()
        sections.append(f'internal static class {cls}\n{{\n' + '\n\n'.join('    ' + constant(source, name) for name in names) + '\n}\n')
    source = (ROOT / 'PokeIdleMulti/RedeemLog.cs').read_text()
    prefix = source[:source.index('internal sealed class RedeemLogWindow')]
    prefix = prefix[:prefix.rfind('}') + 1]
    # The generated file already has its file-scoped namespace.
    prefix = prefix[prefix.index('internal sealed class RedeemLog'):]
    # Linux has no Windows recycle bin. Keep the cleared file as a dated backup.
    prefix = prefix.replace('FileSystem.DeleteFile(path, UIOption.OnlyErrorDialogs, RecycleOption.SendToRecycleBin);',
                            'File.Move(path, path + ".deleted-" + DateTime.UtcNow.ToString("yyyyMMddHHmmssfff"));')
    sections.append(prefix + '\n')
    return '\n'.join(sections)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != result:
            raise SystemExit('Upstream scripts changed. Run: python3 linux/tools/sync-upstream.py')
    else:
        TARGET.write_text(result)
